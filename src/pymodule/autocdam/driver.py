from .multisystem import MultiSystemCalculator, build_systems
from .search import (CHECKPOINT_GROUP, CalculationInput, FittingDriver,
                     default_quality_check)

# Default parameters: metal LJ sigma/epsilon with wide UFF-scaled soft bounds.
DEFAULT_PARAMETERS = {"metal_lj_sigma": "uff", "metal_lj_epsilon": "uff"}
# search={"method": "staged", ...}: coarse-to-fine region settings.
STAGED_DEFAULTS = {
    "max_iterations": 3,
    "samples_per_stage": 10,
    "shrink_fraction": 0.5,
    "seed": 42
}
SEARCH_METHODS = ("staged", "bayesian")


class AutoCDAM:
    """
    Fits the parameters of a cationic dummy-atom model (CDAM) of a metal ion.

    Settings are attributes (see ``_input_keywords`` and ``update_settings``);
    the study itself (candidate, targets, parameters, systems) is given to
    ``setup`` or directly to ``fit``. ``search_method`` selects the staged
    (default) or the Bayesian search; ``geometries`` repeats the search per
    dummy geometry and keeps the best.

    Collaborators (``generator``, ``calculator``, ``evaluator``) can be replaced
    by objects with the same result contracts before ``setup``.

    :param comm:
        The MPI communicator.
    :param ostream:
        The output stream.
    """

    def __init__(self, comm=None, ostream=None):
        """
        Initializes the AutoCDAM driver with default settings.
        """

        if comm is None:
            comm = MPI.COMM_WORLD

        if ostream is None:
            if comm.Get_rank() == mpi_master():
                ostream = OutputStream(sys.stdout)
            else:
                ostream = OutputStream(None)

        # MPI information
        self.comm = comm
        self.rank = self.comm.Get_rank()
        self.nodes = self.comm.Get_size()

        # output stream
        self.ostream = ostream

        # search
        self.search_method = 'staged'
        self.geometries = []
        self.seed = 42
        self.objective_threshold = None

        # staged search
        self.max_iterations = STAGED_DEFAULTS['max_iterations']
        self.samples_per_stage = STAGED_DEFAULTS['samples_per_stage']
        self.shrink_fraction = STAGED_DEFAULTS['shrink_fraction']

        # Bayesian search
        for key, value in SEARCH_DEFAULTS.items():
            if key != 'seed':
                setattr(self, key, deepcopy(value))

        # calculations
        self.pilot = False
        self.work_dir = None
        self.md_options = None
        self.fep_options = None
        self.qm_options = None

        # timing and profiling
        self.timing = False
        self.profiling = False

        # files
        self.filename = None
        self.cache = True
        self.restart = False

        # collaborators and hooks
        self.generator = None
        self.calculator = None
        self.evaluator = None
        self.quality_check = default_quality_check
        self.openmm_template = None

        self._input_keywords = {
            'autocdam': {
                'search_method': ('str_lower', 'staged or bayesian search'),
                'geometries': ('raw', 'dummy geometries searched one by one'),
                'seed': ('int', 'random seed of the search'),
                'objective_threshold':
                    ('float', 'objective that counts as converged'),
                'max_iterations': ('int', 'staged: number of stages'),
                'samples_per_stage': ('int', 'staged: candidates per stage'),
                'shrink_fraction':
                    ('float', 'staged: width kept per refinement'),
                'mode': ('str_lower', 'Bayesian: weighted, constrained, pareto'),
                'max_evaluations': ('int', 'Bayesian: calculated candidates'),
                'initial_samples': ('int', 'Bayesian: space-filling design size'),
                'initial_design': ('str_lower', 'Bayesian: sobol or lhs'),
                'batch_size': ('int', 'Bayesian: candidates per step'),
                'pool_size': ('int', 'Bayesian: acquisition pool size'),
                'n_mc': ('int', 'Bayesian: Monte Carlo draws'),
                'noise': ('bool', 'Bayesian: learn observation noise'),
                'local_refinement':
                    ('bool', 'Bayesian: polish the best pool point'),
                'duplicate_tolerance':
                    ('float', 'Bayesian: minimum unit-cube distance'),
                'acquisition_tolerance':
                    ('float', 'Bayesian: stagnation threshold'),
                'patience': ('int', 'Bayesian: quiet steps before stopping'),
                'cost_aware': ('bool', 'Bayesian: improvement per second'),
                'cost_exponent': ('float', 'Bayesian: cost exponent'),
                'screening': ('raw', 'Bayesian: cheap pre-ranking settings'),
                'max_bound_expansions':
                    ('int', 'Bayesian: widenings of soft bounds'),
                'bound_expansion_factor':
                    ('float', 'Bayesian: widening fraction of the width'),
                'bound_expansion_evaluations':
                    ('int', 'Bayesian: extra budget per widening'),
                'pilot': ('bool', 'short MD workflow test'),
                'work_dir': ('str', 'working directory of the calculations'),
                'md_options': ('raw', 'MD protocol settings'),
                'fep_options': ('raw', 'solvation FEP settings'),
                'qm_options': ('raw', 'QM single-point settings'),
                'timing': ('bool', 'print timing of the fit stages'),
                'profiling': ('bool', 'print profiling information'),
                'filename':
                    ('str', 'run file <filename>.h5: checkpoint, cache, result'),
                'cache': ('bool', 'reuse calculated properties'),
                'restart': ('bool', 'resume from the checkpoint in the run file'),
            },
        }

    def print_keywords(self):
        """
        Prints the input keywords of the AutoCDAM driver.
        """

        print_keywords(self._input_keywords, self.ostream)

    def print_attributes(self):
        """
        Prints the attributes of the AutoCDAM driver.
        """

        print_attributes(self._input_keywords, self.ostream)

    def update_settings(self, settings):
        """
        Updates the settings of the AutoCDAM driver.

        :param settings:
            The dictionary of settings; unknown keys are an error.
        """

        keywords = {
            key: val[0] for key, val in self._input_keywords['autocdam'].items()
        }
        unknown = sorted(set(settings) - set(keywords))
        assert_msg_critical(
            not unknown, f'AutoCDAM: unknown settings {unknown}')
        parse_input(self, keywords, settings)

    def get_references(self):
        """
        Gets the references of the methods used by this study.

        :return:
            The list of reference strings.
        """

        references = [
            # cationic dummy atom model
            'Y.-P. Pang, J. Mol. Model. 1999, 5, 196',
        ]
        candidate = getattr(self, 'candidate', None)
        if candidate is not None and candidate.potential_form == 'lj12_6_4':
            references.append('P. Li and K. M. Merz, J. Chem. Theory Comput. '
                              '2014, 10, 289')
        # Gaussian-process surrogates of both searches (scikit-learn)
        references.append('F. Pedregosa et al., J. Mach. Learn. Res. '
                          '2011, 12, 2825')
        return references

    def print_references(self):
        """
        Prints the references of the methods used by this study.
        """

        self.ostream.print_blank()
        for reference in self.get_references():
            self.ostream.print_reference('Reference: ' + reference)
        self.ostream.print_blank()
        self.ostream.flush()

    def _search_settings(self):
        """
        Gets the settings of the selected search.

        :return:
            The keyword arguments of the search driver.
        """

        assert_msg_critical(
            self.search_method in SEARCH_METHODS,
            f'AutoCDAM: search_method must be one of {SEARCH_METHODS}')
        if self.search_method == 'staged':
            return {
                'max_iterations': int(self.max_iterations),
                'samples_per_stage': int(self.samples_per_stage),
                'shrink_fraction': float(self.shrink_fraction),
                'seed': int(self.seed),
            }
        return {
            'search': {key: getattr(self, key) for key in SEARCH_DEFAULTS}
        }

    def _calculator_options(self):
        """
        Gets the options passed to every property calculation.

        :return:
            The calculator options (only the settings that are given).
        """

        options = {
            name: deepcopy(getattr(self, name))
            for name in ('work_dir', 'md_options', 'fep_options', 'qm_options')
            if getattr(self, name) is not None
        }
        if self.pilot:
            options['md_options'] = {
                'pilot': True,
                **options.get('md_options', {})
            }
        return options

    def setup(self,
              candidate: CDAMCandidate,
              fit_targets: Mapping[str, FitTarget | Mapping[str, Any]] |
              list[FitTarget],
              parameters: Mapping[str, Any] | None = None,
              systems: Mapping[str, Mapping[str, Any] | FrameworkSystem] |
              None = None,
              fit_parameters: Mapping[str, Mapping[str, Any]] |
              list[ParameterSpec] | None = None) -> None:
        """
        Sets up the study without starting calculations.

        :param candidate:
            The CDAM candidate (ion model) to fit.
        :param fit_targets:
            The fit targets (mapping of name to target settings, or a list).
        :param parameters:
            The adjustable parameters in compact form (default: metal LJ
            sigma and epsilon with UFF-based bounds).
        :param systems:
            The named systems (aqueous ion, frameworks) the targets refer to.
        :param fit_parameters:
            Explicit parameter specifications instead of ``parameters``.
        """

        ostream = self.ostream
        self.candidate = candidate
        self.calculator_options = self._calculator_options()
        self.fitting_options = {
            "objective_threshold": self.objective_threshold,
            "quality_check": self.quality_check,
            "checkpoint_file": self.filename,
            **self._search_settings()
        }
        self.search = self.fitting_options.get('search')
        self.geometries = list(self.geometries or [])

        # Targets. Monitors are reported, never optimized: they are calculated
        # once for the final result unless metadata asks for evaluate="always".
        self.targets = coerce_targets(fit_targets)
        self.search_targets = [
            t for t in self.targets
            if not t.is_monitor or t.metadata.get("evaluate") == "always"
        ]
        self.monitor_targets = [
            t for t in self.targets if t not in self.search_targets
        ]
        assert_msg_critical(
            bool(self.search_targets),
            "at least one required or weighted target is needed to fit")

        for geometry in self.geometries:
            assert_msg_critical(
                geometry in CDAMCandidate.geometries,
                f"unsupported geometry {geometry!r} in geometries")

        self.parameter_specs = self._resolve_parameters(parameters,
                                                        fit_parameters)

        # Collaborators: generator -> (system router) -> (cache) calculator -> evaluator.
        if self.generator is None:
            self.generator = CoordinateGenerator(ostream=ostream)
        # Keep the user's calculator so a repeated setup does not wrap the
        # router or cache of an earlier one.
        if not hasattr(self, '_base_calculator'):
            self._base_calculator = self.calculator
        self.calculator = (self._base_calculator
                           if self._base_calculator is not None else
                           Calculator(comm=self.comm, ostream=ostream))
        self.systems = self._build_systems(systems, ostream)
        self.parameter_warnings = self._ineffective_parameter_warnings()
        if self.cache:
            # Calculated properties are kept in the run file, so a later run
            # with the same filename reuses them.
            self.calculator = CachedCalculator(self.calculator,
                                               self.filename,
                                               write=self.rank == mpi_master())
        self._resolve_md_protocol()
        if self.evaluator is None:
            self.evaluator = Evaluator(ostream=ostream)

        self.fitting_driver: FittingDriver | BayesianFittingDriver | None = None
        self.generated_batch: GeneratedBatch | None = None
        self.last_calculation: CalculationResult | None = None

    # ----------------------------------------------------------------- setup

    def _resolve_parameters(self, parameters,
                            fit_parameters) -> list[ParameterSpec]:
        """Parameter specs from ``parameters`` (compact form) or ``fit_parameters``."""
        candidate = self.candidate
        assert_msg_critical(
            parameters is None or fit_parameters is None,
            "use either parameters or fit_parameters, not both")
        if fit_parameters is not None:
            specs = coerce_parameter_specs(fit_parameters)
            unknown = {spec.name for spec in specs} - candidate.parameter_names
            assert_msg_critical(
                not unknown, f"unsupported CDAM parameters: {sorted(unknown)}")
            return specs
        current = {
            name: getattr(candidate, name) for name in candidate.parameter_names
        }
        return parse_parameters(
            parameters if parameters is not None else DEFAULT_PARAMETERS,
            current=current,
            allowed=candidate.parameter_names,
            aliases=candidate.parameter_aliases,
            references=reference_bounds(candidate.metal))

    def _build_systems(self, systems, ostream) -> MultiSystemCalculator | None:
        """Route targets to named systems; None keeps the single aqueous calculator."""
        if systems is None:
            assert_msg_critical(
                all(t.system is None for t in self.targets),
                "targets name a system but no systems were defined")
            return None
        router = build_systems(systems, self.targets, self.calculator, ostream)
        self.calculator = router
        return router

    def _ineffective_parameter_warnings(self) -> list[str]:
        """Warn about adjustable parameters no fitted system can respond to."""
        if self.systems is None:
            return []
        used = {self.systems.system_of(t) for t in self.targets}
        if used & self.systems.aqueous_names:
            return []
        ineffective = None
        for name in used:
            names = set(self.systems.systems[name].ineffective_parameters(
                self.parameter_specs))
            ineffective = names if ineffective is None else ineffective & names
        warnings = [
            f"WARNING: parameter {name!r} cannot affect any fitted system; it is "
            "unidentifiable and should be fixed"
            for name in sorted(ineffective or ())
        ]
        for warning in warnings:
            self.ostream.print_warning(warning)
        self.ostream.flush()
        return warnings

    def _resolve_md_protocol(self) -> None:
        """Store the full MD protocol in the options (and so in checkpoints).

        Later changes to library defaults then cannot silently change a resumed
        study.
        """
        aqueous_md_targets = [
            t for t in self.search_targets
            if t.property_name in {"IOD", "CN"} and
            (not self.systems or
             self.systems.system_of(t) in self.systems.aqueous_names)
        ]
        aqueous = self.systems.aqueous if self.systems is not None else self.calculator
        aqueous = aqueous.inner if isinstance(aqueous,
                                              CachedCalculator) else aqueous
        if isinstance(aqueous, Calculator) and aqueous_md_targets:
            self.calculator_options["md_options"] = md_settings(
                self.calculator_options.get("md_options"))

    def _prepare_template(self) -> None:
        """Build the shared solvent template once when the calculator needs it."""
        if all(target.property_name == "QM_ENERGY" for target in self.targets):
            return
        if self.openmm_template is None and getattr(
                self.calculator, "requires_openmm_systems", False):
            self.openmm_template = self.generator.create_openmm_template(
                self.candidate)

    # ------------------------------------------------------- single steps

    def _parameter_set(self, parameters) -> ParameterSet:
        """Use the initial study point when explicit parameters are omitted."""
        if isinstance(parameters, ParameterSet):
            return parameters
        if parameters is None:
            parameters = {
                spec.name: spec.initial for spec in self.parameter_specs
            }
        return ParameterSet(dict(parameters))

    def generate(self,
                 parameters: ParameterSet | Mapping[str, float] | None = None):
        """
        Generates the CDAM batch of one parameter set.

        The batch is also kept as ``generated_batch``.

        :param parameters:
            The parameter values (default: the initial study point).

        :return:
            The generated batch.
        """

        self.generated_batch = self.generator.generate_parameter_batch(
            self.candidate, [self._parameter_set(parameters)],
            openmm_template=self.openmm_template)[0]
        return self.generated_batch

    def calculate(self,
                  parameters: ParameterSet | Mapping[str, float] | None = None,
                  *,
                  batch: GeneratedBatch | None = None) -> CalculationResult:
        """
        Calculates the CDAM properties of one parameter set.

        Without ``batch`` the batch is generated from ``parameters``; with only
        ``batch`` its own parameters are used. The result is also kept as
        ``last_calculation``.

        :param parameters:
            The parameter values (default: the initial study point).
        :param batch:
            A previously generated batch.

        :return:
            The calculation result.
        """

        if parameters is None and batch is not None and batch.parameters is not None:
            parameter_set = batch.parameters
        else:
            parameter_set = self._parameter_set(parameters)
        if batch is None:
            self._prepare_template()
            batch = self.generate(parameter_set)
        self.last_calculation = self.calculator.calculate(
            batch, parameter_set, self.targets, **self.calculator_options)
        return self.last_calculation

    def evaluate(
            self,
            calculation: CalculationResult | None = None) -> EvaluationResult:
        """
        Compares a calculation result against the targets.

        :param calculation:
            The calculation result (default: the latest calculation, or a new
            calculation at the initial study point).

        :return:
            The evaluation result.
        """

        result = calculation if calculation is not None else self.last_calculation
        if result is None:
            result = self.calculate()
        return self.evaluator.evaluate(result, self.targets)

    # ------------------------------------------------------------------- fit

    def fit(self,
            candidate: CDAMCandidate | None = None,
            fit_targets=None,
            parameters=None,
            systems=None,
            fit_parameters=None) -> FitResult:
        """
        Runs the configured search and returns the finalized result.

        :param candidate:
            The CDAM candidate; with ``fit_targets`` it sets up the study
            (see ``setup``). Omit both after an explicit ``setup``.
        :param fit_targets:
            The fit targets.
        :param parameters:
            The adjustable parameters in compact form.
        :param systems:
            The named systems the targets refer to.
        :param fit_parameters:
            Explicit parameter specifications instead of ``parameters``.

        :return:
            The fit result.
        """

        if candidate is not None or fit_targets is not None:
            self.setup(candidate, fit_targets, parameters, systems,
                       fit_parameters)
        assert_msg_critical(
            hasattr(self, 'candidate'),
            'AutoCDAM: give candidate and fit_targets to fit() or setup()')
        resume = bool(self.restart)
        self.print_references()

        profiler = Profiler({
            'timing': self.timing,
            'profiling': self.profiling,
        })
        profiler.set_timing_key('AutoCDAM fit')

        profiler.start_timer('Template')
        self._prepare_template()
        study_metadata = self._study_metadata()
        profiler.stop_timer('Template')

        profiler.start_timer('Search')
        if self.geometries:
            result = self._fit_geometries(study_metadata, resume)
        else:
            self.fitting_driver = self._make_fitting_driver(study_metadata)
            result = self.fitting_driver.fit(resume=resume)
            if self.fitting_driver.table.samples:
                self.last_calculation = self.fitting_driver.table.samples[
                    -1].calculation
        profiler.stop_timer('Search')

        result.warnings.extend(self.parameter_warnings)
        if self.systems is not None:
            result.diagnostics["systems"] = reporting.system_report(
                self.systems, self._samples(), self.candidate.water_model)
        if self.geometries:
            self.openmm_template = None

        profiler.start_timer('Monitors')
        result = self._finalize(self._add_monitors(result))
        profiler.stop_timer('Monitors')

        if self.filename is not None and self.rank == mpi_master():
            result.save(self.filename)

        profiler.end(self.ostream)
        return result

    def _study_metadata(self) -> dict[str, Any]:
        """What defines this study; checkpoints only resume when it matches."""
        template = self.candidate.to_generated_batch()
        metadata = dict(template.metadata)
        metadata["candidate_template"] = asdict(template.system)
        metadata["calculator_options"] = self.calculator_options
        if self.systems is not None:
            # Baselines are prepared once here; fingerprints guard resume.
            metadata["systems"] = {
                name: ("aqueous" if system is None else {
                    "fingerprint": system.prepare_baseline().fingerprint,
                    "target": system.labels[system.target_index],
                    "representation": system.representation,
                    "protocol": system.protocol
                }) for name, system in self.systems.systems.items()
            }
        return metadata

    def _make_stage_inputs(self, proposals, sample_ids):
        """Yield one independent generated input per proposal (or its generation error)."""
        for parameters, sample_id in zip(proposals, sample_ids):
            try:
                batch = self.generator.generate_parameter_batch(
                    self.candidate, [parameters],
                    openmm_template=self.openmm_template,
                    sample_ids=[sample_id])[0]
                yield CalculationInput(batch, dict(self.calculator_options))
            except Exception as exc:
                yield exc

    def _make_fitting_driver(self, study_metadata, checkpoint_group=None):
        """The Bayesian or the staged driver, as ``search`` selected."""
        options = dict(self.fitting_options)
        if checkpoint_group is not None:
            options["checkpoint_group"] = checkpoint_group
        if self.search is not None:
            options["search"] = self.search
        driver = FittingDriver if self.search is None else BayesianFittingDriver
        return driver(self.parameter_specs,
                      self.search_targets,
                      self.calculator,
                      self.evaluator,
                      self._make_stage_inputs,
                      study_metadata=study_metadata,
                      comm=self.comm,
                      ostream=self.ostream,
                      **options)

    def _fit_geometries(self, study_metadata, resume) -> FitResult:
        """One full search per dummy geometry; keep the best (feasible first, then objective).

        Each geometry gets its own solvent template and checkpoint group
        (``autocdam/checkpoint_<geometry>`` in the run file).
        """
        base_candidate = self.candidate
        results, drivers = {}, {}
        for geometry in self.geometries:
            self.candidate = base_candidate.with_geometry(geometry)
            self.openmm_template = None
            self._prepare_template()
            metadata = deepcopy(study_metadata)
            metadata.update(self.candidate.metadata())
            group = f"{CHECKPOINT_GROUP}_{geometry}"
            driver = self._make_fitting_driver(metadata, group)
            saved = (self.filename is not None and
                     read_h5_group(self.filename, group) is not None)
            results[geometry] = driver.fit(resume=resume and saved)
            drivers[geometry] = driver
        best = min(results,
                   key=lambda g: (not results[g].diagnostics.get(
                       "feasible", False), results[g].objective))
        self.candidate = base_candidate.with_geometry(best)
        self.fitting_driver = drivers[best]
        result = results[best]
        result.diagnostics["geometry"] = best
        result.diagnostics["geometry_results"] = {
            geometry: {
                "objective": r.objective,
                "feasible": r.diagnostics.get("feasible"),
                "converged": r.converged,
                "parameters": r.parameters.to_dict(),
                "n_evaluations": r.diagnostics.get("n_calculations")
            } for geometry, r in results.items()
        }
        return result

    # -------------------------------------------------------------- report

    def _samples(self) -> list:
        """Calculated samples of the surrogate search; empty if none was run."""
        return self.fitting_driver.table.samples if self.fitting_driver else []

    def _add_monitors(self, result: FitResult) -> FitResult:
        """Calculate monitored targets once, for the best evaluated candidate."""
        if not self.monitor_targets or not result.diagnostics.get(
                "best_properties"):
            return result
        self._prepare_template()
        batch = self.generate(result.parameters)
        calculation = self.calculator.calculate(batch, result.parameters,
                                                self.monitor_targets,
                                                **self.calculator_options)
        evaluation = self.evaluator.evaluate(calculation, self.monitor_targets)
        result.diagnostics["monitor"] = reporting.monitor_report(
            calculation, evaluation, self.monitor_targets)
        if calculation.failed:
            result.diagnostics["monitor_failure"] = calculation.failure_reason
        return result

    def _finalize(self, result: FitResult) -> FitResult:
        """Add cost, definitions, bound warnings, validation status, and every evaluation."""
        diagnostics = result.diagnostics
        # After the monitors, so the final HFE/FEP cost is included.
        diagnostics["cost"] = reporting.cost_report(self._samples(),
                                                    self.calculator)
        final_bounds = diagnostics.get("final_bounds", {})
        diagnostics["parameter_definitions"] = reporting.parameter_definitions(
            self.parameter_specs, final_bounds)
        diagnostics["objectives"] = reporting.objective_definitions(
            self.targets)
        diagnostics["target_metal"] = self.candidate.metal
        reporting.add_validation_status(result)
        warnings = reporting.bound_warnings(self.parameter_specs,
                                            result.parameters.values,
                                            final_bounds)
        diagnostics["bound_warnings"] = warnings
        for warning in warnings:
            if warning not in result.warnings:
                result.warnings.append(warning)
                self.ostream.print_warning(warning)
        self.ostream.flush()
        if self.fitting_driver is not None:
            diagnostics["evaluations"] = reporting.evaluation_records(
                self._samples(), self.evaluator, self.search_targets)
        return result

    def export_fitted_model(self, path=None):
        """
        Writes the fitted model: a directory with PDB/XML, systems and provenance.

        :param path:
            The output directory.

        :return:
            The paths of the written files (an empty list on non-master ranks).
        """

        assert_msg_critical(self.fitting_driver is not None,
                            "fit() before exporting a fitted model")
        assert_msg_critical(path is not None,
                            "give an output directory for the fitted model")
        parameters = self._best_parameters()
        if self.rank != mpi_master():
            return []
        return export_cdam_model(path, self.candidate, parameters,
                                 self.systems)

    def _best_parameters(self) -> dict[str, float]:
        """Measured best parameters of the search; raises ValueError if none."""
        if self.fitting_driver is not None:
            best, _ = self.fitting_driver._observed_best()
            if best is not None:
                return best.parameters.to_dict()
        raise ValueError("no usable fitted candidate to export")
